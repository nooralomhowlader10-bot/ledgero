// Helper Functions
export function t(key, lang = 'bn') {
  const entry = translations[key];
  if (!entry) return key;
  return entry[lang] || entry['bn'] || key;
}

export function getDayName(dayIndex, lang = 'bn') {
  return t(`day_${dayIndex}`, lang);
}

export function getTimeGreeting(hour, lang = 'bn') {
  if (hour >= 5 && hour < 12) return { text: t('greeting_morning', lang), emoji: '☀️' };
  if (hour >= 12 && hour < 15) return { text: t('greeting_noon', lang), emoji: '🌤️' };
  if (hour >= 15 && hour < 17) return { text: t('greeting_afternoon', lang), emoji: '🌅' };
  if (hour >= 17 && hour < 19) return { text: t('greeting_evening', lang), emoji: '🌆' };
  return { text: t('greeting_night', lang), emoji: '🌙' };
}

